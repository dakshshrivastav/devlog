/**
 * Core entities: sessions, evidence, transcripts, measurements.
 *
 * These schemas are the single source of truth for both the server and the
 * client. Nothing in `src/` may define its own copy of a shape that lives here.
 */
import { z } from 'zod';

/* -------------------------------------------------------------------------- */
/* Primitives                                                                  */
/* -------------------------------------------------------------------------- */

/** ISO-8601 instant in UTC, or null when the evidence carries no reliable time. */
export const InstantSchema = z.string().nullable();
export type Instant = z.infer<typeof InstantSchema>;

/**
 * The canonical citation label rendered as `[voice 14:02]`, `[photo 2]`,
 * `[commit c4e12a]`. Generated by the pipeline, never by the model.
 */
export const SourceTagSchema = z.string().min(1);
export type SourceTag = z.infer<typeof SourceTagSchema>;

export const IdSchema = z.string().min(1);

/** Stable ids of evidence items backing a claim. Empty means ungrounded. */
export const SourcesSchema = z.array(IdSchema);
export type Sources = z.infer<typeof SourcesSchema>;

/* -------------------------------------------------------------------------- */
/* Evidence                                                                    */
/* -------------------------------------------------------------------------- */

export const EvidenceKindSchema = z.enum(['voice', 'photo', 'commit', 'note', 'measurement']);
export type EvidenceKind = z.infer<typeof EvidenceKindSchema>;

export const WordSchema = z.object({
  text: z.string(),
  start: z.number(),
  end: z.number(),
});
export type Word = z.infer<typeof WordSchema>;

export const VoicePayloadSchema = z.object({
  audioId: z.string(),
  /** Audio-relative offsets in seconds — not wall clock. */
  span: z.object({ startSec: z.number(), endSec: z.number() }),
  quote: z.string().optional(),
  words: z.array(WordSchema).optional(),
  transcriptId: z.string().optional(),
});
export type VoicePayload = z.infer<typeof VoicePayloadSchema>;

export const PhotoPayloadSchema = z.object({
  mediaId: z.string(),
  /** Resolved by the store: `/api/sessions/:id/media/...` or a remote fixture URL. */
  url: z.string(),
  caption: z.string().optional(),
  exif: z
    .object({
      takenAt: z.string().nullish(),
      device: z.string().nullish(),
      note: z.string().nullish(),
    })
    .optional(),
});
export type PhotoPayload = z.infer<typeof PhotoPayloadSchema>;

export const DiffLineSchema = z.object({
  lineNum: z.number().int(),
  content: z.string(),
  kind: z.enum(['context', 'added', 'removed']),
});
export type DiffLine = z.infer<typeof DiffLineSchema>;

export const CommitPayloadSchema = z.object({
  hash: z.string(),
  subject: z.string(),
  branch: z.string().optional(),
  authoredAt: z.string().optional(),
  filesChanged: z.number().int().optional(),
  diffFile: z.string().optional(),
  diff: z.array(DiffLineSchema).optional(),
});
export type CommitPayload = z.infer<typeof CommitPayloadSchema>;

/**
 * A measured value. Created only from speech, typed notes, or a git diff —
 * never inferred from a photograph. See docs/BUILD_PLAN.md §1.2.
 */
export const TracePointSchema = z.object({ t: z.number(), v: z.number() });
export type TracePoint = z.infer<typeof TracePointSchema>;

export const MeasurementPayloadSchema = z.object({
  quantity: z.string(),
  value: z.string(),
  unit: z.string().optional(),
  instrument: z.string().optional(),
  role: z.enum(['baseline', 'event', 'threshold', 'result']).optional(),
  /** Only populated when the builder actually supplied samples. */
  trace: z.array(TracePointSchema).optional(),
});
export type MeasurementPayload = z.infer<typeof MeasurementPayloadSchema>;

export const NotePayloadSchema = z.object({
  text: z.string(),
  origin: z.enum(['capture', 'gap-answer', 'manual']),
});
export type NotePayload = z.infer<typeof NotePayloadSchema>;

export const EvidenceItemSchema = z.object({
  id: IdSchema,
  kind: EvidenceKindSchema,
  sourceTag: SourceTagSchema,
  label: z.string(),
  detail: z.string().optional(),
  instant: InstantSchema,
  /** True when the timestamp came from a timezone-naive source such as EXIF. */
  instantIsNaive: z.boolean().default(false),
  /** Stable tie-breaker for the timeline ordering policy. */
  order: z.number().int(),
  /** Provenance statement shown next to the item, e.g. "EXIF 14:08:19 UTC". */
  verification: z.string(),
  voice: VoicePayloadSchema.optional(),
  photo: PhotoPayloadSchema.optional(),
  commit: CommitPayloadSchema.optional(),
  measurement: MeasurementPayloadSchema.optional(),
  note: NotePayloadSchema.optional(),
});
export type EvidenceItem = z.infer<typeof EvidenceItemSchema>;

export const EvidenceListSchema = z.array(EvidenceItemSchema);

/* -------------------------------------------------------------------------- */
/* Transcript                                                                  */
/* -------------------------------------------------------------------------- */

export const TranscriptSegmentSchema = z.object({
  id: IdSchema,
  audioId: z.string(),
  text: z.string(),
  start: z.number(),
  end: z.number(),
  words: z.array(WordSchema).optional(),
  /** Which evidence item this segment became, once the timeline is built. */
  evidenceId: IdSchema.optional(),
});
export type TranscriptSegment = z.infer<typeof TranscriptSegmentSchema>;

export const TranscriptSchema = z.object({
  provider: z.enum(['elevenlabs-scribe-v2', 'local-whisper', 'fixture', 'none']),
  model: z.string().optional(),
  language: z.string().optional(),
  segments: z.array(TranscriptSegmentSchema),
  /** Whether word-level timing is genuinely available. Never synthesized. */
  wordTimingAvailable: z.boolean().default(false),
});
export type Transcript = z.infer<typeof TranscriptSchema>;

/* -------------------------------------------------------------------------- */
/* Sessions                                                                    */
/* -------------------------------------------------------------------------- */

export const SessionModeSchema = z.enum(['batch', 'live']);
export type SessionMode = z.infer<typeof SessionModeSchema>;

export const SessionStatusSchema = z.enum([
  'draft',
  'capturing',
  'processing',
  'ready',
  'failed',
]);
export type SessionStatus = z.infer<typeof SessionStatusSchema>;

export const SessionCountsSchema = z.object({
  voice: z.number().int(),
  photo: z.number().int(),
  commit: z.number().int(),
  note: z.number().int(),
  measurement: z.number().int(),
  evidence: z.number().int(),
});
export type SessionCounts = z.infer<typeof SessionCountsSchema>;

export const GroundingSchema = z.object({
  sourced: z.number().int(),
  unsourced: z.number().int(),
  percent: z.number(),
});
export type Grounding = z.infer<typeof GroundingSchema>;

export const SessionSchema = z.object({
  id: IdSchema,
  name: z.string(),
  slug: z.string(),
  mode: SessionModeSchema,
  status: SessionStatusSchema,
  createdAt: z.string(),
  startedAt: InstantSchema,
  endedAt: InstantSchema,
  durationSec: z.number().nullable(),
  repoPath: z.string().nullable(),
  repoBranch: z.string().nullable(),
  headCommit: z.string().nullable(),
  /** True when this session is served from fixtures with no provider calls. */
  mock: z.boolean().default(false),
  counts: SessionCountsSchema,
  grounding: GroundingSchema,
  error: z.string().nullable(),
});
export type Session = z.infer<typeof SessionSchema>;
