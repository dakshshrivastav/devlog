/**
 * Deterministic markdown renderers.
 *
 * These documents are pure functions of the structured session state, so they
 * regenerate exactly — including after a gap answer changes a BOM row. Nothing
 * here is model-generated, which means they render identically in mock mode and
 * in a real run. Model-authored prose (README narrative, incident analysis) is
 * injected when present and omitted when not.
 */
import type {
  Artifact,
  Bom,
  EvidenceItem,
  GapItem,
  HardwareGraph,
  Incident,
  ObservationNote,
  Session,
} from '../../../shared/schema/index';
import { formatClock, formatDuration, formatPercent } from '../../../shared/format';

function tags(sources: readonly string[], evidenceById: Map<string, EvidenceItem>): string {
  const labels = sources
    .map((id) => evidenceById.get(id)?.sourceTag ?? id)
    .filter((v, i, all) => all.indexOf(v) === i);
  return labels.length > 0 ? ` ${labels.map((l) => `[${l}]`).join(' ')}` : '';
}

function header(session: Session, title: string): string[] {
  return [
    `# ${title}`,
    '',
    `> Generated by devlog from session **${session.name}** (${session.mode} capture).`,
    `> Evidence: ${session.counts.evidence} items · ${formatEvidenceLine(session)}.`,
    `> Grounding: ${formatPercent(session.grounding.percent, 1)} of statements cite a source.`,
    '',
  ];
}

function formatEvidenceLine(session: Session): string {
  const parts: string[] = [];
  if (session.counts.voice) parts.push(`${session.counts.voice} voice note${session.counts.voice === 1 ? '' : 's'}`);
  if (session.counts.photo) parts.push(`${session.counts.photo} photo${session.counts.photo === 1 ? '' : 's'}`);
  if (session.counts.commit) parts.push(`${session.counts.commit} commit${session.counts.commit === 1 ? '' : 's'}`);
  if (session.counts.measurement) {
    parts.push(`${session.counts.measurement} measurement${session.counts.measurement === 1 ? '' : 's'}`);
  }
  if (session.counts.note) parts.push(`${session.counts.note} note${session.counts.note === 1 ? '' : 's'}`);
  return parts.length > 0 ? parts.join(', ') : 'nothing recorded yet';
}

export function renderBomMd(
  bom: Bom,
  session: Session,
  evidence: readonly EvidenceItem[]
): string {
  const byId = new Map(evidence.map((e) => [e.id, e]));
  const lines = header(session, 'Bill of Materials');

  if (bom.revision) lines.push(`Revision: ${bom.revision}`, '');

  lines.push(
    `Items: ${bom.stats.items} · Verified: ${bom.stats.verified} · Pending clarification: ${bom.stats.needsPn} · ${formatPercent(
      bom.stats.percentVerified,
      0
    )} spec match`,
    ''
  );

  if (bom.items.length === 0) {
    lines.push('_No components extracted yet._', '');
  } else {
    lines.push('| Designator | Component | Specification | Qty | Status | Source |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    for (const item of bom.items) {
      const source = item.sources
        .map((id) => byId.get(id)?.sourceTag ?? id)
        .join(', ');
      lines.push(
        `| ${item.designator} | ${item.name} | ${item.spec} | ${item.qty} | ${item.status} | ${source || '—'} |`
      );
    }
    lines.push('');
  }

  if (bom.stats.totalCost) {
    lines.push(
      `Estimated total: ${bom.stats.totalCost.amount.toFixed(2)} ${bom.stats.totalCost.currency}`,
      ''
    );
  } else if (bom.items.length > 0) {
    lines.push('_Unit costs are not reported: no sourced pricing evidence in this session._', '');
  }

  if (bom.tools.length > 0) {
    lines.push('## Bench tools and test equipment', '');
    for (const tool of bom.tools) {
      lines.push(`- **${tool.code}** — ${tool.name}${tags(tool.sources, byId)}`);
      if (tool.description) lines.push(`  - ${tool.description}`);
      if (tool.specs) lines.push(`  - ${tool.specs}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

export function renderGapsMd(
  gaps: readonly GapItem[],
  session: Session,
  evidence: readonly EvidenceItem[]
): string {
  const byId = new Map(evidence.map((e) => [e.id, e]));
  const lines = header(session, 'Gaps');
  const open = gaps.filter((g) => g.status === 'open');
  const resolved = gaps.filter((g) => g.status === 'resolved');
  const deferred = gaps.filter((g) => g.status === 'deferred');

  lines.push(`Open: ${open.length} · Resolved: ${resolved.length} · Deferred: ${deferred.length}`, '');

  if (gaps.length === 0) {
    lines.push('_No gaps. Every required detail was present in the evidence._', '');
    return lines.join('\n');
  }

  if (open.length > 0) {
    lines.push('## Open', '');
    for (const gap of open) {
      lines.push(`### ${gap.number}. ${gap.question}`);
      lines.push('');
      lines.push(`- Priority: ${gap.priority}`);
      lines.push(`- Needed for: ${gap.targetDoc}`);
      lines.push(`- ${gap.description}`);
      lines.push('');
    }
  }

  if (resolved.length > 0) {
    lines.push('## Resolved', '');
    for (const gap of resolved) {
      const resolution = gap.resolution;
      const source = resolution?.evidenceId ? tags([resolution.evidenceId], byId) : '';
      lines.push(`### ${gap.number}. ${gap.question}`);
      lines.push('');
      lines.push(`- Answer: **${resolution?.answer ?? '—'}**${source}`);
      if (resolution) {
        lines.push(`- Method: ${resolution.method} · ${resolution.resolvedAt}`);
      }
      lines.push('');
    }
  }

  if (deferred.length > 0) {
    lines.push('## Deferred', '');
    for (const gap of deferred) {
      lines.push(`- ${gap.number}. ${gap.question} — ${gap.resolution?.answer ?? 'deferred'}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

export function renderObserverNotesMd(
  observations: readonly ObservationNote[],
  session: Session,
  evidence: readonly EvidenceItem[]
): string {
  const byId = new Map(evidence.map((e) => [e.id, e]));
  const lines = header(session, 'Observer Notes');
  lines.push(
    'Written in the third person from the perspective of an observer at the bench.',
    ''
  );

  if (observations.length === 0) {
    lines.push('_No observations recorded._', '');
    return lines.join('\n');
  }

  for (const note of observations) {
    const source = note.evidenceId ? tags([note.evidenceId], byId) : '';
    lines.push(`- **${note.timeLabel}** — ${note.title}${source}`);
    if (note.body) lines.push(`  - ${note.body}`);
  }
  lines.push('');
  return lines.join('\n');
}

export function renderTroubleshootingMd(
  incidents: readonly Incident[],
  session: Session,
  evidence: readonly EvidenceItem[]
): string {
  const byId = new Map(evidence.map((e) => [e.id, e]));
  const lines = header(session, 'Troubleshooting');

  if (incidents.length === 0) {
    lines.push('_No incidents recorded in this session._', '');
    return lines.join('\n');
  }

  for (const incident of incidents) {
    lines.push(`## Incident ${incident.number}: ${incident.title}`, '');
    lines.push(`- Level: ${incident.level} · Status: ${incident.status}${tags(incident.sources, byId)}`);
    if (incident.phase) lines.push(`- Phase: ${incident.phase}`);
    if (incident.detectedAt) lines.push(`- Detected: ${incident.detectedAt}`);
    if (incident.resolvedAt) lines.push(`- Resolved: ${incident.resolvedAt}`);
    if (incident.telemetryTarget) lines.push(`- Telemetry target: ${incident.telemetryTarget}`);
    lines.push('');
    lines.push(`**Symptom.** ${incident.symptom}`, '');
    if (incident.measurements.length > 0) {
      lines.push('**Measurements.**', '');
      for (const m of incident.measurements) {
        lines.push(`- ${m.label}: ${m.value}${tags(m.sources, byId)}`);
      }
      lines.push('');
    }
    lines.push(`**Root cause.** ${incident.rootCause}`, '');
    lines.push(`**Fix.** ${incident.fix}`, '');
    if (incident.verification) lines.push(`**Verification.** ${incident.verification}`, '');
    if (incident.rulesLearned.length > 0) {
      lines.push('**Bench rules learned.**', '');
      for (const rule of incident.rulesLearned) {
        lines.push(`- ${rule.title} — ${rule.body}${tags(rule.sources, byId)}`);
      }
      lines.push('');
    }
  }

  return lines.join('\n');
}

export interface ReadmeProse {
  title: string;
  standfirst?: string;
  overview?: string;
  architecture?: string;
  troubleshooting?: string;
}

/**
 * README is the one artifact whose prose is model-authored. The structure,
 * citations, BOM table and diagram references are deterministic; the narrative
 * sections are filled only when the model supplied them.
 */
export function renderReadmeMd(input: {
  prose: ReadmeProse | null;
  session: Session;
  evidence: readonly EvidenceItem[];
  bom: Bom;
  hardware: HardwareGraph;
  incidents: readonly Incident[];
  artifacts: readonly Artifact[];
}): string {
  const { prose, session, evidence, bom, hardware, incidents, artifacts } = input;
  const byId = new Map(evidence.map((e) => [e.id, e]));
  const title = prose?.title?.trim() || session.name;
  const lines: string[] = [`# ${title}`, ''];

  if (prose?.standfirst) lines.push(prose.standfirst, '');

  lines.push(
    `Session **${session.name}** · ${formatDuration(session.durationSec)} · ${formatEvidenceLine(session)}.`,
    ''
  );

  lines.push('## 1. Overview', '');
  lines.push(
    prose?.overview ??
      '_No overview synthesized yet. Run the pipeline over a capture to generate it._',
    ''
  );

  lines.push('## 2. Hardware architecture', '');
  if (prose?.architecture) lines.push(prose.architecture, '');
  if (hardware.nodes.length > 0) {
    lines.push('| Node | Kind | Value | Source |');
    lines.push('| --- | --- | --- | --- |');
    for (const node of hardware.nodes) {
      const source = node.sources.map((id) => byId.get(id)?.sourceTag ?? id).join(', ');
      const designator = node.designator ? `${node.designator} · ` : '';
      lines.push(
        `| ${designator}${node.name} | ${node.kind} | ${node.value ?? '—'} | ${source || '—'} |`
      );
    }
    lines.push('');
  }
  const diagrams = artifacts.filter((a) => a.kind === 'mermaid');
  if (diagrams.length > 0) {
    for (const diagram of diagrams) lines.push(`- \`${diagram.name}\` — ${diagram.summary ?? diagram.title ?? ''}`);
    lines.push('');
  }

  lines.push('## 3. Bill of materials', '');
  if (bom.items.length === 0) {
    lines.push('_No components extracted yet._', '');
  } else {
    for (const item of bom.items) {
      const source = item.sources.map((id) => byId.get(id)?.sourceTag ?? id).join(', ');
      lines.push(`- ${item.designator} ${item.name} — qty ${item.qty}${source ? ` [${source}]` : ''}`);
    }
    lines.push('');
  }

  lines.push('## 4. Troubleshooting', '');
  if (prose?.troubleshooting) lines.push(prose.troubleshooting, '');
  if (incidents.length === 0 && !prose?.troubleshooting) {
    lines.push('_No incidents recorded._', '');
  } else {
    for (const incident of incidents) {
      lines.push(`### Incident ${incident.number}: ${incident.title}`, '');
      lines.push(`- Symptom: ${incident.symptom}`);
      lines.push(`- Root cause: ${incident.rootCause}`);
      lines.push(`- Fix: ${incident.fix}`);
      if (incident.verification) lines.push(`- Verification: ${incident.verification}`);
      lines.push('');
    }
  }

  lines.push('---', '');
  lines.push(
    `_Generated by devlog from ${formatEvidenceLine(session)}. Every fact above cites the evidence it came from; anything missing is listed in \`GAPS.md\`._`,
    ''
  );

  return lines.join('\n');
}

export function renderIndexMd(session: Session, artifacts: readonly Artifact[]): string {
  const lines = [`# ${session.name} — documentation bundle`, ''];
  lines.push(`Generated ${new Date().toISOString()}.`, '');
  lines.push('| File | Kind | Status | Summary |');
  lines.push('| --- | --- | --- | --- |');
  for (const artifact of artifacts) {
    lines.push(
      `| \`${artifact.name}\` | ${artifact.kind} | ${artifact.statusLabel} | ${artifact.summary ?? '—'} |`
    );
  }
  lines.push('');
  const openGaps = artifacts.filter((a) => a.status === 'needs-input').length;
  if (openGaps > 0) {
    lines.push(`> ${openGaps} artifact(s) are waiting on a gap answer.`, '');
  }
  return lines.join('\n');
}

export function clockOf(instant: string | null): string {
  return formatClock(instant);
}
